"""Train the walking-speed Random Forest and write an evaluation report.

Requires the backend package: `pip install -e backend`.

    python scripts/make_synthetic_gait.py --out data/synthetic
    python scripts/train_model.py --data data/synthetic

Evaluation uses GroupKFold by subject: no person appears in both the training
and test folds. Splitting by trial would leak subject identity (gait is very
person-specific) and inflate scores.

Two normalization settings are evaluated:
- subject_id: z-score per subject over all their trials (mirrors the original study).
- trial_id:   z-score per recording (what the demo can do with a single upload).
The deployed model uses `trial_id` so training matches serving.
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score
from sklearn.model_selection import GroupKFold

from app.ml.classifier import DEFAULT_MODEL_PATH, ModelBundle, feature_matrix, save_bundle
from app.ml.features import model_features
from app.ml.normalization import NORMALIZATION_GROUPS, zscore_by_group
from app.ml.schema import read_recording

DEPLOYED_NORMALIZATION = "trial_id"
CLASSES = ["slow", "normal", "fast"]
N_SPLITS = 5
SEED = 0


def make_model() -> RandomForestClassifier:
    """Random Forest config. 300 trees is past the point where accuracy stops changing."""
    return RandomForestClassifier(n_estimators=300, random_state=SEED, n_jobs=-1)


def load_dataset(data_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Return (all recordings concatenated, labels with trial_id/subject_id/speed)."""
    labels = pd.read_csv(data_dir / "labels.csv")
    frames = [read_recording(data_dir / f"{tid}.csv") for tid in labels["trial_id"]]
    return pd.concat(frames, ignore_index=True), labels


def build_features(raw: pd.DataFrame, labels: pd.DataFrame, group: str) -> list[dict]:
    """Feature dict per trial, in `labels` order."""
    normalized = zscore_by_group(raw, group)
    rows = []
    for tid in labels["trial_id"]:
        mask = raw["trial_id"] == tid
        rows.append(model_features(raw[mask], normalized[mask]))
    return rows


def cross_validate(x: np.ndarray, y: np.ndarray, groups: np.ndarray) -> dict:
    """Out-of-fold predictions with GroupKFold by subject."""
    pred = np.empty_like(y)
    for train, test in GroupKFold(n_splits=N_SPLITS).split(x, y, groups):
        pred[test] = make_model().fit(x[train], y[train]).predict(x[test])
    return {
        "accuracy": float(accuracy_score(y, pred)),
        "macro_f1": float(f1_score(y, pred, average="macro")),
        "confusion_matrix": confusion_matrix(y, pred, labels=CLASSES).tolist(),
    }


def _confusion_md(cm: list[list[int]]) -> str:
    lines = ["| true \\ pred | " + " | ".join(CLASSES) + " |", "|---" * (len(CLASSES) + 1) + "|"]
    lines += [
        f"| {c} | " + " | ".join(map(str, row)) + " |" for c, row in zip(CLASSES, cm, strict=True)
    ]
    return "\n".join(lines)


def write_report(path: Path, results: dict, info: dict, importances: list[tuple]) -> None:
    """Write a Markdown training report."""
    md = [
        "# Speed classifier training report",
        "",
        "> **SYNTHETIC DATA.** These numbers come from synthetic recordings generated by",
        "> `scripts/make_synthetic_gait.py`. They only show that the pipeline works and say",
        "> nothing about performance on real gait data.",
        "",
        f"- Generated: {info['created_at']}",
        f"- Trials: {info['n_trials']} from {info['n_subjects']} subjects; features: {info['n_features']}",
        f"- Evaluation: GroupKFold by subject, {N_SPLITS} folds",
        f"- Majority-class baseline accuracy: {info['baseline_accuracy']:.3f}",
        f"- Deployed model normalization: `{DEPLOYED_NORMALIZATION}`",
        "",
    ]
    for group, r in results.items():
        md += [
            f"## Normalization: `{group}`",
            "",
            f"- Accuracy: {r['accuracy']:.3f}",
            f"- Macro F1: {r['macro_f1']:.3f}",
            "",
            _confusion_md(r["confusion_matrix"]),
            "",
        ]
    md += ["## Top 10 feature importances (deployed model)", ""]
    md += ["| feature | importance |", "|---|---|"]
    md += [f"| `{name}` | {imp:.3f} |" for name, imp in importances[:10]]
    path.write_text("\n".join(md) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Train the walking-speed classifier.")
    parser.add_argument("--data", type=Path, default=Path("data/synthetic"))
    parser.add_argument("--out", type=Path, default=DEFAULT_MODEL_PATH)
    parser.add_argument("--trained-on", default="synthetic")
    args = parser.parse_args()

    raw, labels = load_dataset(args.data)
    y = labels["speed"].to_numpy()
    groups = labels["subject_id"].to_numpy()

    results, deployed_rows = {}, None
    for group in NORMALIZATION_GROUPS:
        rows = build_features(raw, labels, group)
        feature_names = list(rows[0])
        results[group] = cross_validate(feature_matrix(rows, feature_names), y, groups)
        print(f"{group}: accuracy={results[group]['accuracy']:.3f}")
        if group == DEPLOYED_NORMALIZATION:
            deployed_rows = rows

    feature_names = list(deployed_rows[0])
    model = make_model().fit(feature_matrix(deployed_rows, feature_names), y)
    info = {
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "trained_on": args.trained_on,
        "n_trials": len(labels),
        "n_subjects": int(labels["subject_id"].nunique()),
        "n_features": len(feature_names),
        "baseline_accuracy": float(labels["speed"].value_counts(normalize=True).max()),
        "cv": results,
    }
    save_bundle(
        ModelBundle(
            model=model,
            feature_names=feature_names,
            normalization=DEPLOYED_NORMALIZATION,
            trained_on=args.trained_on,
            metadata=info,
        ),
        args.out,
    )
    args.out.with_suffix(".json").write_text(json.dumps(info, indent=2) + "\n")
    importances = sorted(
        zip(feature_names, model.feature_importances_, strict=True), key=lambda p: -p[1]
    )
    write_report(args.out.with_name("training_report.md"), results, info, importances)
    print(f"Saved {args.out}")


if __name__ == "__main__":
    main()
